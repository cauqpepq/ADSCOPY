const TABLES: Record<'en' | 'ru' | 'zh', Partial<Record<TranslationKey, string>>> = {
  en: EN,
  ru: RU,
  zh: ZH
}

export function useT(): (key: TranslationKey, vars?: Record<string, string | number>) => string {
  const lang = useStore((s) => s.lang)
  return (key, vars) => {
    const raw = TABLES[lang][key] ?? EN[key] ?? key
    if (!vars) return raw
    return Object.entries(vars).reduce(
      (acc, [k, v]) => acc.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v)),
      raw
    )
  }
}

export function tx(lang: 'en' | 'ru' | 'zh', key: TranslationKey): string {
  return TABLES[lang][key] ?? EN[key] ?? key
}
